-- ---------------------------------------------------------------------------
-- 1. Platform-owner identity
-- ---------------------------------------------------------------------------
create table if not exists public.platform_admins (
  user_id uuid primary key references auth.users (id) on delete cascade,
  role text not null default 'owner'
    check (role in ('owner', 'support', 'billing')),
  created_at timestamptz not null default now(),
  created_by uuid references auth.users (id) on delete set null
);

comment on table public.platform_admins is
  'FitDesk platform staff. Separate from gym administrators. Insert only with service-role SQL.';

alter table public.platform_admins enable row level security;
revoke all on table public.platform_admins from public, anon, authenticated;

-- ---------------------------------------------------------------------------
-- 2. Manual subscription tracking (no payment gateway)
-- ---------------------------------------------------------------------------
create table if not exists public.gym_subscriptions (
  id uuid primary key default gen_random_uuid(),
  gym_id uuid not null references public.gyms (id) on delete cascade,
  plan text not null default 'trial',
  status text not null default 'trialing'
    check (status in ('trialing', 'active', 'past_due', 'cancelled')),
  trial_ends_on date,
  current_period_end date,
  amount_inr integer check (amount_inr is null or amount_inr >= 0),
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists gym_subscriptions_gym_created_idx
  on public.gym_subscriptions (gym_id, created_at desc);

alter table public.gym_subscriptions enable row level security;
revoke all on table public.gym_subscriptions from public, anon, authenticated;

-- ---------------------------------------------------------------------------
-- 3. Platform audit log
-- ---------------------------------------------------------------------------
create table if not exists public.platform_audit_log (
  id bigint generated by default as identity primary key,
  actor_id uuid references auth.users (id) on delete set null,
  gym_id uuid references public.gyms (id) on delete set null,
  action text not null,
  details jsonb,
  created_at timestamptz not null default now()
);

create index if not exists platform_audit_log_gym_created_idx
  on public.platform_audit_log (gym_id, created_at desc);

alter table public.platform_audit_log enable row level security;
revoke all on table public.platform_audit_log from public, anon, authenticated;

-- ---------------------------------------------------------------------------
-- 4. Guard
-- ---------------------------------------------------------------------------
create or replace function public.platform_assert()
returns uuid
language plpgsql
stable
security definer
set search_path = public, pg_temp
as $$
declare
  v_user uuid := auth.uid();
begin
  if v_user is null then
    raise exception 'AUTH_REQUIRED' using errcode = 'P0001';
  end if;

  if not exists (
    select 1 from public.platform_admins where user_id = v_user
  ) then
    raise exception 'PLATFORM_OWNER_REQUIRED' using errcode = '42501';
  end if;

  return v_user;
end;
$$;

revoke all on function public.platform_assert() from public, anon, authenticated;
grant execute on function public.platform_assert() to authenticated;

create or replace function public.platform_me()
returns jsonb
language plpgsql
stable
security definer
set search_path = public, pg_temp
as $$
declare
  v_user uuid := auth.uid();
  v_role text;
begin
  if v_user is null then
    return jsonb_build_object('is_platform_owner', false, 'role', null);
  end if;

  select role into v_role
    from public.platform_admins
   where user_id = v_user;

  return jsonb_build_object(
    'is_platform_owner', v_role is not null,
    'role', v_role
  );
end;
$$;

revoke all on function public.platform_me() from public, anon, authenticated;
grant execute on function public.platform_me() to authenticated;

-- ---------------------------------------------------------------------------
-- 5. Platform gym list
-- ---------------------------------------------------------------------------
create or replace function public.platform_list_gyms(
  p_search text default null,
  p_status text default null,
  p_limit integer default 50,
  p_offset integer default 0
)
returns table (
  gym_id uuid,
  public_id text,
  name text,
  owner_email text,
  is_active boolean,
  member_count integer,
  admin_count integer,
  subscription_status text,
  trial_ends_on date,
  current_period_end date,
  created_at timestamptz,
  total_count bigint
)
language plpgsql
stable
security definer
set search_path = public, auth, pg_temp
as $$
declare
  v_search text := nullif(btrim(coalesce(p_search, '')), '');
  v_status text := lower(nullif(btrim(coalesce(p_status, '')), ''));
  v_limit integer := greatest(1, least(coalesce(p_limit, 50), 200));
  v_offset integer := greatest(coalesce(p_offset, 0), 0);
begin
  perform public.platform_assert();

  return query
  with base as (
    select
      g.id as gym_id,
      g.public_id,
      g.name,
      u.email::text as owner_email,
      g.is_active,
      (select count(*)::integer
         from public.profiles p
        where p.gym_id = g.id and p.is_admin = false) as member_count,
      (select count(*)::integer
         from public.profiles p
        where p.gym_id = g.id and p.is_admin = true) as admin_count,
      s.status as subscription_status,
      s.trial_ends_on,
      s.current_period_end,
      g.created_at
    from public.gyms g
    left join auth.users u on u.id = g.owner_id
    left join lateral (
      select gs.status, gs.trial_ends_on, gs.current_period_end
        from public.gym_subscriptions gs
       where gs.gym_id = g.id
       order by gs.created_at desc
       limit 1
    ) s on true
    where (v_search is null
           or g.name ilike '%' || v_search || '%'
           or g.public_id ilike '%' || v_search || '%'
           or u.email ilike '%' || v_search || '%')
      and (v_status is null
           or v_status = 'all'
           or (v_status = 'active' and g.is_active = true)
           or (v_status = 'suspended' and g.is_active = false))
  )
  select
    b.gym_id,
    b.public_id,
    b.name,
    b.owner_email,
    b.is_active,
    b.member_count,
    b.admin_count,
    b.subscription_status,
    b.trial_ends_on,
    b.current_period_end,
    b.created_at,
    count(*) over() as total_count
  from base b
  order by b.created_at desc, b.gym_id
  limit v_limit
  offset v_offset;
end;
$$;

revoke all on function public.platform_list_gyms(text, text, integer, integer) from public, anon, authenticated;
grant execute on function public.platform_list_gyms(text, text, integer, integer) to authenticated;

-- ---------------------------------------------------------------------------
-- 6. Platform totals
-- ---------------------------------------------------------------------------
create or replace function public.platform_dashboard_totals()
returns jsonb
language plpgsql
stable
security definer
set search_path = public, pg_temp
as $$
declare
  v_today date := (now() at time zone 'Asia/Kolkata')::date;
begin
  perform public.platform_assert();

  return jsonb_build_object(
    'total_gyms', (select count(*)::integer from public.gyms),
    'active_gyms', (select count(*)::integer from public.gyms where is_active),
    'suspended_gyms', (select count(*)::integer from public.gyms where not is_active),
    'total_members', (select count(*)::integer from public.profiles where is_admin = false),
    'total_admins', (select count(*)::integer from public.profiles where is_admin = true),
    'trialing_gyms', (
      select count(distinct gs.gym_id)::integer
        from public.gym_subscriptions gs
       where gs.status = 'trialing'
         and gs.created_at = (
           select max(x.created_at) from public.gym_subscriptions x where x.gym_id = gs.gym_id
         )
    ),
    'past_due_gyms', (
      select count(distinct gs.gym_id)::integer
        from public.gym_subscriptions gs
       where gs.status = 'past_due'
         and gs.created_at = (
           select max(x.created_at) from public.gym_subscriptions x where x.gym_id = gs.gym_id
         )
    ),
    'revenue_month_inr', (
      select coalesce(sum(pay.total_amount_inr), 0)::integer
        from public.payments pay
       where pay.status = 'approved'
         and (pay.reviewed_at at time zone 'Asia/Kolkata')::date >= date_trunc('month', v_today)::date
    )
  );
end;
$$;

revoke all on function public.platform_dashboard_totals() from public, anon, authenticated;
grant execute on function public.platform_dashboard_totals() to authenticated;

-- ---------------------------------------------------------------------------
-- 7. Platform gym detail
-- ---------------------------------------------------------------------------
create or replace function public.platform_gym_detail(p_gym_id uuid)
returns jsonb
language plpgsql
stable
security definer
set search_path = public, auth, pg_temp
as $$
declare
  v_result jsonb;
begin
  perform public.platform_assert();

  select jsonb_build_object(
    'gym', to_jsonb(g),
    'owner_email', u.email::text,
    'member_count', (
      select count(*)::integer from public.profiles p
       where p.gym_id = g.id and p.is_admin = false
    ),
    'admin_count', (
      select count(*)::integer from public.profiles p
       where p.gym_id = g.id and p.is_admin = true
    ),
    'subscription', (
      select to_jsonb(s)
        from public.gym_subscriptions s
       where s.gym_id = g.id
       order by s.created_at desc
       limit 1
    ),
    'recent_audit', (
      select coalesce(jsonb_agg(to_jsonb(a) order by a.created_at desc), '[]'::jsonb)
        from (
          select id, actor_id, action, details, created_at
            from public.platform_audit_log
           where gym_id = g.id
           order by created_at desc
           limit 10
        ) a
    )
  )
    into v_result
    from public.gyms g
    left join auth.users u on u.id = g.owner_id
   where g.id = p_gym_id;

  if v_result is null then
    raise exception 'GYM_NOT_FOUND' using errcode = 'P0001';
  end if;

  return v_result;
end;
$$;

revoke all on function public.platform_gym_detail(uuid) from public, anon, authenticated;
grant execute on function public.platform_gym_detail(uuid) to authenticated;

-- ---------------------------------------------------------------------------
-- 8. Suspend / activate
-- ---------------------------------------------------------------------------
create or replace function public.platform_set_gym_active(
  p_gym_id uuid,
  p_active boolean,
  p_reason text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_actor uuid := public.platform_assert();
  v_reason text := nullif(btrim(coalesce(p_reason, '')), '');
  v_exists boolean;
begin
  if p_gym_id is null then
    raise exception 'GYM_NOT_FOUND' using errcode = 'P0001';
  end if;

  select exists(select 1 from public.gyms where id = p_gym_id) into v_exists;
  if not v_exists then
    raise exception 'GYM_NOT_FOUND' using errcode = 'P0001';
  end if;

  if p_active then
    update public.gyms
       set is_active = true,
           suspended_at = null,
           suspension_reason = null,
           updated_at = now()
     where id = p_gym_id;
  else
    update public.gyms
       set is_active = false,
           suspended_at = now(),
           suspension_reason = v_reason,
           updated_at = now()
     where id = p_gym_id;
  end if;

  insert into public.platform_audit_log (actor_id, gym_id, action, details)
  values (
    v_actor,
    p_gym_id,
    case when p_active then 'gym_activated' else 'gym_suspended' end,
    jsonb_build_object('active', p_active, 'reason', v_reason)
  );

  return public.platform_gym_detail(p_gym_id);
end;
$$;

revoke all on function public.platform_set_gym_active(uuid, boolean, text) from public, anon, authenticated;
grant execute on function public.platform_set_gym_active(uuid, boolean, text) to authenticated;

-- ---------------------------------------------------------------------------
-- 9. Manual subscription editor
-- ---------------------------------------------------------------------------
create or replace function public.platform_upsert_subscription(
  p_gym_id uuid,
  p_plan text,
  p_status text,
  p_trial_ends_on date default null,
  p_current_period_end date default null,
  p_amount_inr integer default null,
  p_notes text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_actor uuid := public.platform_assert();
  v_plan text := nullif(btrim(coalesce(p_plan, '')), '');
  v_status text := lower(nullif(btrim(coalesce(p_status, '')), ''));
  v_row public.gym_subscriptions;
begin
  if not exists (select 1 from public.gyms where id = p_gym_id) then
    raise exception 'GYM_NOT_FOUND' using errcode = 'P0001';
  end if;

  if v_plan is null then
    raise exception 'PLAN_REQUIRED' using errcode = '22023';
  end if;

  if v_status not in ('trialing', 'active', 'past_due', 'cancelled') then
    raise exception 'INVALID_SUBSCRIPTION_STATUS' using errcode = '22023';
  end if;

  if p_amount_inr is not null and p_amount_inr < 0 then
    raise exception 'INVALID_AMOUNT' using errcode = '22023';
  end if;

  insert into public.gym_subscriptions
    (gym_id, plan, status, trial_ends_on, current_period_end, amount_inr, notes)
  values
    (p_gym_id, v_plan, v_status, p_trial_ends_on, p_current_period_end, p_amount_inr, nullif(btrim(coalesce(p_notes, '')), ''))
  returning * into v_row;

  insert into public.platform_audit_log (actor_id, gym_id, action, details)
  values (
    v_actor,
    p_gym_id,
    'subscription_updated',
    jsonb_build_object(
      'plan', v_row.plan,
      'status', v_row.status,
      'trial_ends_on', v_row.trial_ends_on,
      'current_period_end', v_row.current_period_end,
      'amount_inr', v_row.amount_inr
    )
  );

  return to_jsonb(v_row);
end;
$$;

revoke all on function public.platform_upsert_subscription(uuid, text, text, date, date, integer, text) from public, anon, authenticated;
grant execute on function public.platform_upsert_subscription(uuid, text, text, date, date, integer, text) to authenticated;

commit;
